// Precompiles src/assets/tester_configuration.schema.json into a standalone validator
// (src/core/testerValidator.generated.js). The app's Content Security Policy forbids eval,
// so ajv must not compile the schema at runtime. Run: npm run gen:validator
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync(new URL("../src/assets/tester_configuration.schema.json", import.meta.url), "utf8"));
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
const code = standaloneCode(ajv, ajv.compile(schema));
const out = new URL("../src/core/testerValidator.generated.js", import.meta.url);
const text = "// @ts-nocheck\n// Generated by scripts/gen-tester-validator.mjs from tester_configuration.schema.json – do not edit.\n" + code + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) { console.error("testerValidator.generated.js is out of date: npm run gen:validator"); process.exit(1); }
} else writeFileSync(out, text);
